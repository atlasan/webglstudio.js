<?php

	/*
		FBX converter endpoint used by plugins/scripts/fbxconv.js
		- POST an "fbx" file: converts it with fbx-conv and returns the scene (g3dj) and texture paths
		- GET ?done=temp/phpXXXXXX : frees the files of that conversion

		Security notes:
		- only files created by this script inside temp/ can be deleted (name must match the PHP upload temp name pattern)
		- old conversions are removed automatically after $TEMP_MAX_AGE seconds, even if "done" is never called
		- the upload size is limited by $MAX_UPLOAD_SIZE (and by PHP's upload_max_filesize / post_max_size)
		- media embedded in the FBX is extracted inside temp/ (web accessible), so anything that is not an image is deleted
	*/

	$MAX_UPLOAD_SIZE = 100 * 1024 * 1024; //100 MB
	$TEMP_MAX_AGE = 60 * 60; //1 hour
	$TEMP_FOLDER = "temp";
	$ALLOWED_MEDIA_EXTENSIONS = array( "png","jpg","jpeg","gif","bmp","tga","dds","webp","tif","tiff" ); //textures extracted from the FBX

	chdir( __DIR__ ); //paths below are relative to this script

	function deleteDir($dirPath) {
		if (! is_dir($dirPath)) {
			throw new InvalidArgumentException("$dirPath must be a directory");
		}
		if (substr($dirPath, strlen($dirPath) - 1, 1) != '/') {
			$dirPath .= '/';
		}
		$files = glob($dirPath . '*', GLOB_MARK);
		foreach ($files as $file) {
			if (is_dir($file)) {
				deleteDir($file);
			} else {
				unlink($file);
			}
		}
		rmdir($dirPath);
	}

	//removes every file generated for one conversion: base, base.fbx, base.g3dj, base.fbm/
	function deleteConversion( $filebasename )
	{
		foreach( array( "", ".fbx", ".g3dj" ) as $ext )
			if( is_file( $filebasename . $ext ) )
				unlink( $filebasename . $ext );
		if( is_dir( $filebasename . ".fbm" ) )
			deleteDir( $filebasename . ".fbm" );
	}

	//removes conversions older than $max_age seconds
	function cleanOldConversions( $folder, $max_age )
	{
		$now = time();
		foreach( glob( $folder . "/php*" ) as $path )
		{
			if( ( $now - filemtime( $path ) ) < $max_age )
				continue;
			if( is_dir( $path ) )
				deleteDir( $path );
			else
				unlink( $path );
		}
	}

	function fail( $msg, $code = 400 )
	{
		http_response_code( $code );
		header("Content-type: application/json");
		die( json_encode( array( "status" => 0, "error" => $msg ) ) );
	}

	if( !is_dir( $TEMP_FOLDER ) )
		mkdir( $TEMP_FOLDER, 0770 );

	cleanOldConversions( $TEMP_FOLDER, $TEMP_MAX_AGE );

	if(isset($_REQUEST["done"]))
	{
		//only accept names generated by this script: "temp/phpXXXXXX" (or just "phpXXXXXX")
		$name = $_REQUEST["done"];
		if( !is_string($name) )
			fail("invalid name");
		if( strpos( $name, $TEMP_FOLDER . "/" ) === 0 )
			$name = substr( $name, strlen( $TEMP_FOLDER ) + 1 );
		if( !preg_match( '/^php[A-Za-z0-9]{1,32}$/', $name ) )
			fail("invalid name");

		deleteConversion( $TEMP_FOLDER . "/" . $name );
		header("Content-type: application/json");
		die('{"status": 1 }');
	}

	if( $_SERVER["REQUEST_METHOD"] !== "POST" )
		fail("use POST to upload an FBX", 405);

	if(!isset($_FILES["fbx"]) || !is_array($_FILES["fbx"]) || !isset($_FILES["fbx"]["tmp_name"]) || !is_string($_FILES["fbx"]["tmp_name"]))
	{
		$postmaxsize = ini_get("post_max_size");
		fail("FBX not found in request, maybe it was too big. Max size is: " . $postmaxsize);
	}

	$file = $_FILES["fbx"];
	if( $file["error"] !== UPLOAD_ERR_OK )
		fail("upload error code: " . intval( $file["error"] ));
	if( $file["size"] > $MAX_UPLOAD_SIZE )
		fail("FBX too big. Max size is: " . $MAX_UPLOAD_SIZE . " bytes", 413);

	$tempbasename = basename( $file["tmp_name"] ); //"phpSomething"
	if( !preg_match( '/^php[A-Za-z0-9]{1,32}$/', $tempbasename ) ) //never expected, but the name is used in a shell command and in "done"
		$tempbasename = "php" . bin2hex( random_bytes(8) );
	$tempfilename = $TEMP_FOLDER . "/" . $tempbasename; //"temp/phpSomething"

	if( !move_uploaded_file( $file["tmp_name"], $tempfilename ) || !is_file( $tempfilename ) )
		fail("FBX not stored in disk", 500);

	$program = "./fbx-conv-lin64";
	putenv("LD_LIBRARY_PATH=" . __DIR__ );

	$cmd = $program . " -o G3DJ -b 64 " . escapeshellarg( $tempfilename ) . " 2>&1";
	$out = array();
	$str = exec($cmd, $out);
	$output = implode("|", $out);

	header("Content-type: application/json");
	header("X-file-length: " . filesize( $tempfilename ) );

	$filebasename = $tempfilename;

	if( !is_file( $filebasename . ".g3dj" ) )
	{
		deleteConversion( $filebasename );
		fail("error parsing FBX");
	}

	$result = Array();
	$result["status"] = 1;
	$result["scene_path"] = $filebasename . ".g3dj";
	$result["scene_name"] = $filebasename;

	$mediafolder = $filebasename . ".fbm";
	if( is_dir( $mediafolder ) )
	{
		$result["images"] = Array();
		if ($handle = opendir($mediafolder))
		{
			while (false !== ($entry = readdir($handle)))
			{
				if ('.' === $entry) continue;
				if ('..' === $entry) continue;
				$entrypath = $mediafolder . "/" . $entry;
				$ext = strtolower( pathinfo( $entry, PATHINFO_EXTENSION ) );
				//never leave scripts (.php, .phtml, .htaccess...) or folders in a public folder
				if( is_dir( $entrypath ) || is_link( $entrypath ) || $entry[0] == "." || !in_array( $ext, $ALLOWED_MEDIA_EXTENSIONS, true ) || substr_count( $entry, "." ) != 1 )
				{
					if( is_dir( $entrypath ) && !is_link( $entrypath ) )
						deleteDir( $entrypath );
					else
						unlink( $entrypath );
					continue;
				}
				$result["images"][] = $entrypath;
			}
			closedir($handle);
		}
	}

	if(isset($_REQUEST["immediate"]))
		$result["scene"] = file_get_contents( $filebasename . ".g3dj" );

	$str = json_encode( $result );
	header("Content-length: " . strlen($str) );

	echo $str;

	//files are kept until the client calls ?done= (it still needs to fetch the textures) or until they expire ($TEMP_MAX_AGE)
?>
